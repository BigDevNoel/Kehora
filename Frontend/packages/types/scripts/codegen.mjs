// Generates src/generated/schemas.ts from the Backend JSON Schemas (ADR-0004).
// Usage: node scripts/codegen.mjs <schema-dir>   (make codegen passes ../Backend/schemas)
// One combined root schema is compiled so every shared type is declared exactly once.
import { readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, join } from "node:path";
import { compile } from "json-schema-to-typescript";

const schemaDir = resolve(process.argv[2] ?? "../../../Backend/schemas");
const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();

const toTitle = (file) =>
  file.replace(".schema.json", "").split("_").map((p) => p[0].toUpperCase() + p.slice(1)).join("");

const root = {
  title: "KehoraSchemas",
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(files.map((f) => [toTitle(f), { $ref: f }])),
};

const ts = await compile(root, "KehoraSchemas", {
  cwd: schemaDir,
  bannerComment:
    "/* Generated by `make codegen` from Backend/schemas/*.schema.json. Do not edit by hand. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  format: true,
  style: { singleQuote: false, printWidth: 100 },
});

const out = join(import.meta.dirname, "..", "src", "generated");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "schemas.ts"), ts);
console.log(`types: wrote ${files.length} schemas to src/generated/schemas.ts`);
